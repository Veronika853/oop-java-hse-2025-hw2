import java.util.List;

/**
 * Интерфейс для объектов, поддерживающих публикацию объявлений.
 * Определяет методы для добавления объявлений и получения их списка.
 */
public interface Publishable {
    /**
     * Публикует новое объявление, добавляя его в ленту новостей.
     *
     * @param message текст объявления
     */
    void publish(String message);

    /**
     * Возвращает список всех объявлений.
     *
     * @return список строк с объявлениями
     */
    List<String> getFeed();
}
