/**
 * Интерфейс, представляющий человека в университетской системе.
 * Определяет метод для получения подробной информации о персоне.
 */
public interface Person {

    /**
     * Возвращает подробную информацию о персоне, такую как идентификатор, имя и другие характеристики.
     *
     * @return строка с информацией о персоне
     */
    String getDetails();
}
